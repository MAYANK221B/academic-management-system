CREATE TABLE course_memberships (
    membership_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    offering_id BIGINT NOT NULL,
    role VARCHAR(20) NOT NULL,
    joined_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_course_memberships_user FOREIGN KEY (user_id)
        REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_course_memberships_offering FOREIGN KEY (offering_id)
        REFERENCES course_offerings(offering_id) ON DELETE RESTRICT,
    CONSTRAINT uk_course_memberships_user_offering UNIQUE (user_id, offering_id),
    CONSTRAINT chk_course_memberships_role CHECK (role IN ('STUDENT', 'PROFESSOR', 'TA'))
);

-- The unique constraint covers user-first membership and authorization lookups.
CREATE INDEX idx_course_memberships_offering ON course_memberships (offering_id);
