CREATE TABLE user_platform_roles (
    user_platform_role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    role VARCHAR(30) NOT NULL,
    CONSTRAINT fk_user_platform_roles_user FOREIGN KEY (user_id)
        REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT uk_user_platform_roles_user_role UNIQUE (user_id, role),
    CONSTRAINT chk_user_platform_roles_role CHECK (role IN ('ACADENCE_ADMIN'))
);
