CREATE TABLE courses (
    course_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code VARCHAR(30) NOT NULL UNIQUE,
    course_name VARCHAR(255) NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE course_offerings (
    offering_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES courses(course_id),
    semester VARCHAR(20) NOT NULL,
    year INTEGER NOT NULL,
    section VARCHAR(20) NOT NULL,
    CONSTRAINT uk_course_offerings_course_term_section UNIQUE (course_id, semester, year, section),
    CONSTRAINT chk_course_offerings_semester CHECK (semester IN ('SPRING', 'SUMMER', 'FALL')),
    CONSTRAINT chk_course_offerings_year CHECK (year > 0)
);
